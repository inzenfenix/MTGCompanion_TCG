#!/usr/bin/env node
/**
 * ROADMAP.md E3c — self-hosts the three things `tesseract.js`'s browser
 * defaults otherwise fetch from a CDN at first OCR use
 * (`ocrExtractor.ts`'s "Known gap" comment used to document this as
 * unsolved):
 *
 *   1. `workerPath`  — `tesseract.js/dist/worker.min.js`, already sitting in
 *      `node_modules` (it's part of the npm package itself, not a download).
 *   2. `corePath`    — `tesseract.js-core`'s WASM engine. Also already in
 *      `node_modules`, but tesseract.js ships several variants (plain/SIMD/
 *      relaxed-SIMD, LSTM-only vs. full) and picks one via runtime feature
 *      detection (see `tesseract.js/src/worker-script/browser/getCore.js`).
 *      This app always calls `createWorker(lang)` with the default OEM
 *      (`OEM.LSTM_ONLY`), so only the 3 `*-lstm.wasm.js`/`.wasm` pairs are
 *      needed — the non-LSTM variants (legacy Tesseract engine) never get
 *      selected and are skipped to avoid shipping ~7MB of dead weight.
 *   3. `langPath`    — the English `.traineddata` itself. NOT part of any
 *      npm package (`tesseract.js` fetches it lazily, at runtime, from
 *      jsdelivr's `@tesseract.js-data` CDN) — this is the one real download
 *      this script does, once, from the exact same CDN URL tesseract.js's
 *      own default would hit, then never again (skipped if already present).
 *
 * Run once after `npm install` (or after bumping `tesseract.js`/
 * `tesseract.js-core` — the copied files must match the installed version,
 * since corePath/workerPath aren't renegotiated at runtime): `npm run
 * setup:tesseract`. Output is gitignored (`public/tesseract/`,
 * `public/tessdata/`) — generated/downloaded, not source, same convention
 * as `public/models/*.onnx` (regenerated by running an export script, not
 * committed).
 *
 * Safe to run without network once already run once: every step is
 * idempotent (copies overwrite, the traineddata download is skipped if the
 * file already exists) — CI/offline dev only needs today's CDN default if
 * this script was never run at all.
 */

import { existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const TESSERACT_JS_DIST = join(ROOT, 'node_modules/tesseract.js/dist');
const TESSERACT_CORE_DIR = join(ROOT, 'node_modules/tesseract.js-core');
const PUBLIC_TESSERACT_DIR = join(ROOT, 'public/tesseract');
const PUBLIC_CORE_DIR = join(PUBLIC_TESSERACT_DIR, 'core');
const PUBLIC_TESSDATA_DIR = join(ROOT, 'public/tessdata');

// Matches `getCore.js`'s own selection set for `lstmOnly=true` (this app's
// only OEM mode) — relaxed-SIMD > SIMD > plain, each as a `.wasm.js` glue
// file that resolves its sibling `.wasm` binary by replacing its own `.js`
// extension (standard Emscripten MODULARIZE pattern — confirmed by
// inspecting the minified glue: no literal filename embedded in it, so both
// files must sit next to each other under the same name minus extension,
// which copying pairs as-is preserves).
const CORE_LSTM_VARIANTS = [
  'tesseract-core-lstm',
  'tesseract-core-simd-lstm',
  'tesseract-core-relaxedsimd-lstm',
];

const LANG = 'eng';
// Same URL tesseract.js's own worker-script/index.js builds by default when
// `langPath` is unset and `lstmOnly` is true — see that file's
// `langPathDownload` line. Pinning the literal URL here (rather than
// re-deriving it from a version string) keeps this script simple; if
// tesseract.js ever changes its data format version, bump this too.
const LANG_DATA_URL = `https://cdn.jsdelivr.net/npm/@tesseract.js-data/${LANG}/4.0.0_best_int/${LANG}.traineddata.gz`;

function copy(src, destDir, filename = undefined) {
  if (!existsSync(src)) {
    throw new Error(`Expected file not found: ${src} — is tesseract.js/tesseract.js-core installed? (npm install)`);
  }
  mkdirSync(destDir, { recursive: true });
  const dest = join(destDir, filename ?? src.split('/').pop());
  copyFileSync(src, dest);
  return dest;
}

/**
 * Downloads the .gz and writes the DECOMPRESSED `.traineddata` (no `.gz`
 * suffix) — real bug found live (ROADMAP.md I17): Android's Gradle/AAPT
 * asset packaging silently gunzips any `.gz`-named asset and strips the
 * extension when it builds the APK (`eng.traineddata.gz` on disk becomes
 * `eng.traineddata` inside the packaged app — confirmed with `unzip -l` on
 * a real built APK), but `ocrExtractor.ts` was still asking tesseract.js to
 * fetch the exact `.gz` name — a real 404 on-device, OCR permanently stuck
 * on "Identifying card" with the pipeline having no error handling either
 * (see runScanPipeline() in ListCard.tsx). Rather than fight Android's
 * repacking, this script now ships the same plain, already-decompressed
 * file everywhere (desktop, mobile web, Android) — `ocrExtractor.ts` asks
 * tesseract.js for the plain name too (`gzip: false` in its `createWorker`
 * call), so there's only one real filename/shape to reason about, matching
 * what Android would produce anyway.
 */
async function downloadDecompressedIfMissing(url, dest) {
  if (existsSync(dest)) {
    console.log(`  already present, skipping download: ${dest}`);
    return;
  }
  console.log(`  downloading ${url}`);
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to download ${url}: HTTP ${res.status}`);
  }
  const gz = Buffer.from(await res.arrayBuffer());
  const { gunzipSync } = await import('node:zlib');
  const buf = gunzipSync(gz);
  mkdirSync(dirname(dest), { recursive: true });
  await import('node:fs/promises').then((fs) => fs.writeFile(dest, buf));
  console.log(`  wrote ${dest} (${(buf.length / 1024 / 1024).toFixed(2)} MB, decompressed from ${(gz.length / 1024 / 1024).toFixed(2)} MB)`);
}

console.log('1/3 — worker.min.js');
copy(join(TESSERACT_JS_DIST, 'worker.min.js'), PUBLIC_TESSERACT_DIR);

console.log('2/3 — tesseract.js-core (LSTM-only wasm variants)');
for (const variant of CORE_LSTM_VARIANTS) {
  copy(join(TESSERACT_CORE_DIR, `${variant}.wasm.js`), PUBLIC_CORE_DIR);
  copy(join(TESSERACT_CORE_DIR, `${variant}.wasm`), PUBLIC_CORE_DIR);
}

console.log('3/3 — English traineddata (decompressed, see downloadDecompressedIfMissing() for why)');
await downloadDecompressedIfMissing(LANG_DATA_URL, join(PUBLIC_TESSDATA_DIR, `${LANG}.traineddata`));

console.log('Done. public/tesseract/ and public/tessdata/ are ready for OCR to run without hitting any CDN.');
